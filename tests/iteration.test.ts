import assert from 'node:assert/strict';
import {fresh} from '../lib/model.ts';
import {cityForDate,cityColor,categoryColor} from '../lib/schedule-colors.ts';
import {recordSchema} from '../lib/validation.ts';
import {projectFromResource} from '../lib/project-transfer.ts';
const trip=(date:string,city:string)=>({...fresh('schedule'),name:'trip',planned:date,time:'09:00',category:'差旅行程',destinationCity:city});
const records=[trip('2026-11-01','北京'),trip('2026-11-05','上海'),trip('2026-11-09','厦门')];
assert.equal(cityForDate(records,'2026-10-31'),'');
assert.equal(cityForDate(records,'2026-11-01'),'北京');
assert.equal(cityForDate(records,'2026-11-04'),'北京');
assert.equal(cityForDate(records,'2026-11-06'),'上海');
assert.equal(cityForDate(records,'2026-11-09'),'厦门');
assert.equal(cityForDate([...records,{...trip('2026-11-03','深圳'),tentative:true}],'2026-11-04'),'北京');
assert.equal(cityForDate([...records,{...trip('2026-11-03','深圳'),status:'已取消'}],'2026-11-04'),'北京');
assert.equal(cityForDate([{...trip('2026-11-03','广州'),category:'线下会议'}],'2026-11-04'),'');
assert.equal(cityColor('北京市'),cityColor('北京'));
assert.equal(new Set(['线上会议','线下会议','直播演讲','拍摄录制'].map(categoryColor)).size,4);
const resource={...fresh('resource'),name:'测试资源',internalContact:true,projectEnabled:true,hiddenFields:['channel'],fieldLabels:{contact:'合作对接'},customFields:[{id:'one',label:'材料',value:'方案'}],notes:[{text:'最初沟通',at:'2026-11-19T00:00:00.000Z',by:'珈珈'}]};
const project=projectFromResource(resource);assert.equal(project.kind,'project');assert.equal(project.sourceResourceId,resource.id);assert.notEqual(project.id,resource.id);assert.equal(projectFromResource(resource).id,project.id);assert.deepEqual(project.notes,resource.notes);
const parsed=recordSchema.parse({...resource,legacyField:'preserved'});assert.equal(parsed.legacyField,'preserved');assert.equal(parsed.internalContact,true);assert.equal(parsed.customFields[0].label,'材料');assert.equal(recordSchema.parse({...fresh('task'),name:'无截止日期',deadline:''}).deadline,'');
assert.equal(recordSchema.safeParse({...fresh('project'),name:'a',notes:[{text:'b',at:'2026-11-19T00:00:00.000Z',by:'珈珈',url:'javascript:alert(1)'}]}).success,false);
console.log('PASS: 城市延续/返厦/待定/取消、类别颜色、独立项目流转、字段保留、空截止日期、链接校验');
const cityOverride = [...records, {...trip('2026-11-03','深圳市'), category:'线下会议'}];
assert.equal(cityForDate(cityOverride,'2026-11-03'),'深圳');
assert.equal(cityForDate(cityOverride,'2026-11-04'),'北京');

